// Bundle attributed Wikimedia previews so Android and offline sessions can display them.
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const photos = require('../src/data/pangasinanPhotos.json');
const directory = path.join(__dirname, '../src/assets/pangasinan');
async function main() {
  await fs.mkdir(directory, { recursive: true });
  const imports = [];
  for (const photo of Object.values(photos).flat()) {
    const ext = new URL(photo.uri).pathname.toLowerCase().endsWith('.png') ? 'png' : 'jpg';
    const filename = crypto.createHash('sha256').update(photo.uri).digest('hex').slice(0, 16) + '.' + ext;
    const file = path.join(directory, filename);
    if (!(await fs.stat(file).catch(() => null))) {
      let saved = false;
      for (let attempt = 0; attempt < 3; attempt++) {
        await new Promise(resolve => setTimeout(resolve, attempt ? 12000 : 1500));
        const url = attempt === 1 ? photo.uri.replace('https://thumb.wikimedia.org/', 'https://upload.wikimedia.org/') : photo.uri;
        const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
        if (!response.ok) continue;
        if (!response.headers.get('content-type')?.startsWith('image/')) throw new Error('Invalid image response');
        await fs.writeFile(file, Buffer.from(await response.arrayBuffer()));
        saved = true;
        break;
      }
      if (!saved) throw new Error(`Could not download ${photo.title}`);
    }
    imports.push(`  ${JSON.stringify(photo.uri)}: require('../assets/pangasinan/${filename}'),`);
    console.log('Bundled ' + photo.title);
  }
  await fs.writeFile(path.join(__dirname, '../src/data/pangasinanPhotoAssets.js'), '// Generated by scripts/download-map-photos.cjs. Credits are in pangasinanPhotos.json.\nexport const photoAssets = {\n' + imports.join('\n') + '\n};\n');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
