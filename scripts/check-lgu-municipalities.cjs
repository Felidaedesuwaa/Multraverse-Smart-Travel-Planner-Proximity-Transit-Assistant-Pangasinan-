const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
;(async () => {
  const source = fs.readFileSync(path.join(root, 'src/data/lguMunicipalities.js'), 'utf8')
  const { lguMunicipalities, getLGUMunicipality, getLGUMapViewport } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`)
  const areas = require('../server/src/data/plannerAreas.json')
  const geometry = require('../src/data/pangasinanMap.json')
  assert.equal(lguMunicipalities.length, 48)
  assert.equal(new Set(lguMunicipalities.map(area => area.name)).size, 48)
  assert.equal(lguMunicipalities.filter(area => area.kind === 'City').length, 4)
  assert.deepEqual(lguMunicipalities.map(({ id, name, kind }) => ({ id, name, kind })), areas)
  for (const area of lguMunicipalities) {
    assert.ok(area.center.lat > 15 && area.center.lat < 17)
    assert.ok(area.center.lng > 119 && area.center.lng < 122)
    assert.ok(Number.isInteger(area.defaultZoom) && area.defaultZoom >= 9 && area.defaultZoom <= 14)
    assert.equal(getLGUMunicipality(` ${area.name.toUpperCase()} `), area)
    assert.equal(getLGUMunicipality(area.id), area)
    if (area.kind === 'City') {
      assert.equal(getLGUMunicipality(`City of ${area.name}`), area)
      assert.equal(getLGUMunicipality(`${area.name} City`), area)
    }
    const [x, y, width, height] = getLGUMapViewport(area).split(' ').map(Number)
    const numbers = geometry.areas.find(item => item.id === area.id).d.match(/-?\d+(?:\.\d+)?/g).map(Number)
    const xs = numbers.filter((_, i) => i % 2 === 0), ys = numbers.filter((_, i) => i % 2 === 1)
    assert.ok(Math.min(...xs) >= x && Math.max(...xs) <= x + width, `${area.name}: horizontal bounds must fit`)
    assert.ok(Math.min(...ys) >= y && Math.max(...ys) <= y + height, `${area.name}: vertical bounds must fit`)
    const zoomed = getLGUMapViewport(area, area.defaultZoom + 1).split(' ').map(Number)
    assert.ok(Math.abs(zoomed[2] * 2 - width) < 0.001)
  }
  for (const invalid of [null, undefined, '', 'Unknown', 'Manila', {}, 'Dagupan OR Bolinao']) assert.equal(getLGUMunicipality(invalid), null)
  assert.equal(fs.readdirSync(path.join(root, 'src/pages')).filter(file => /^LGUDashboard\./.test(file)).length, 1)
  console.log('PASS all 48 LGU names, 4 cities, aliases, coordinate bounds, map viewports and zoom; one shared dashboard')
})().catch(error => { console.error(error); process.exitCode = 1 })
